"""Lab 3: write runs/run_record_facts.md, a factual list copied from logs and git (no interpretation)."""
import re
import subprocess
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
R = BASE / "runs"
out = ["# Lab 3 run record facts (generated by src/make_facts.py; copied from logs and git, not interpreted)", ""]


def git(*a):
    return subprocess.run(["git", *a], cwd=BASE, capture_output=True, text=True).stdout.strip()


out += ["## Software versions (lines copied from runs/s00_env_kafka.log)", ""]
env = (R / "s00_env_kafka.log").read_text().splitlines()
for i, l in enumerate(env):
    if l.startswith("$ ") and any(k in l for k in ["hostname", "uname", "python", "java -version",
                                                   "kafka-topics.sh --version", "import pandas"]):
        nxt = env[i + 1] if i + 1 < len(env) else ""
        out.append(f"- `{l[2:]}` → `{nxt}`")
    if "version 3.5.9" in l or l.startswith("Using Scala version"):
        out.append(f"- `spark-submit --version` → `{l.strip()}`")
out += ["", "## Producer run summaries (copied from runs/*_producer.log)", "",
        "| log | topic | events sent | late | achieved rate | requested rate | seed |",
        "|---|---|---|---|---|---|---|"]
for p in sorted(R.glob("*_producer.log")):
    t = p.read_text()
    g = lambda k: (re.search(rf"^\s+{k}\s+(.+)$", t, re.M) or [None, "-"])[1].strip()
    out.append(f"| {p.name} | {g('topic')} | {g('events sent')} | {g('of which late')} | "
               f"{g('achieved rate')} | {g('requested rate')} | {g('seed')} |")
out += ["", "## Prediction files and the commit that added them", ""]
for p in sorted(R.glob("ex*_prediction.txt")):
    h = git("log", "--diff-filter=A", "--format=%h %cI %s", "--", f"runs/{p.name}")
    out.append(f"- runs/{p.name}: {h}")
out += ["", "## Log files and their first line (UTC time)", ""]
for p in sorted(R.glob("*.log")):
    first = p.read_text().splitlines()[0] if p.stat().st_size else "(empty)"
    out.append(f"- runs/{p.name}: {first}")
(R / "run_record_facts.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
